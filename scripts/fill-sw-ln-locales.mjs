import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..', 'src', 'locales')

function read(lang) {
  return JSON.parse(readFileSync(join(root, `${lang}.json`), 'utf8'))
}

function write(lang, data) {
  writeFileSync(join(root, `${lang}.json`), `${JSON.stringify(data, null, 2)}\n`, 'utf8')
}

