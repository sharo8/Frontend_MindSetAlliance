import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const dir = join(dirname(fileURLToPath(import.meta.url)), '..', 'src', 'locales')

function read(lang) {
  return JSON.parse(readFileSync(join(dir, `${lang}.json`), 'utf8'))
}
function write(lang, data) {
  writeFileSync(join(dir, `${lang}.json`), `${JSON.stringify(data, null, 2)}\n`, 'utf8')
}
function setPath(obj, path, value) {
  const parts = path.split('.')
  let cur = obj
  for (let i = 0; i < parts.length - 1; i++) {
    const p = parts[i]
    if (!cur[p] || typeof cur[p] !== 'object' || Array.isArray(cur[p])) cur[p] = {}
    cur = cur[p]
  }
  cur[parts[parts.length - 1]] = value
}
function pruneTo(src, mask) {
  if (mask == null || typeof mask !== 'object' || Array.isArray(mask)) return src
  const out = {}
  for (const k of Object.keys(mask)) {
    if (!(k in src)) continue
    const mv = mask[k]
    const sv = src[k]
    if (mv && typeof mv === 'object' && !Array.isArray(mv) && sv && typeof sv === 'object' && !Array.isArray(sv)) {
      out[k] = pruneTo(sv, mv)
    } else {
      out[k] = sv
    }
  }
  return out
}

